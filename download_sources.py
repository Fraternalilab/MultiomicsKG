CHUNK_SIZE = 8 * 1024 * 1024


@dataclass
class Source:
    """A downloadable dataset

    kind:
        file       - save the download as-is
        gunzip     - decompress a .gz download into target
        zip_member - extract `member` from a .zip download into target
        tar_member - extract `member` from a tar download into target
                     (decompressed if the member is .gz and target is not)
        tar_dir    - extract members matching `member` (glob) into target dir
        zip_dir    - extract members matching `member` (glob) into target dir
        rsync      - mirror the remote rsync module into target dir
        manual     - no public URL, print `note`
    """

    name: str
    target: str
    url: str = ""
    kind: str = "file"
    member: str = ""
    large: bool = False
    extra_urls: list = field(default_factory=list)
    note: str = ""


