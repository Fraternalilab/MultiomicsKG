"""Downloads the public source datasets referenced by filenames.FileNames.

Files generated by the pipeline itself (SNV-filtered VCFs, VEP outputs, graph
CSVs, scrap files) are not downloaded. Datasets with no public download URL
are listed as manual steps.
"""

