def _fetch(url: str, dest: str):
    """Streams url to dest, resuming from dest.part when the server allows it"""
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    part = dest + ".part"
    offset = os.path.getsize(part) if os.path.exists(part) else 0
    request = urllib.request.Request(url, headers={"User-Agent": "multiomicskg"})
    if offset:
        request.add_header("Range", f"bytes={offset}-")
    with urllib.request.urlopen(request) as response:
        if offset and response.status != 206:
            # server ignored the range request, start over
            offset = 0
        total = response.headers.get("Content-Length")
        total = int(total) + offset if total else None
        logging.info(f"Downloading {url} -> {dest}")
        written = offset
        next_report = written + 1024 * CHUNK_SIZE
        with open(part, "ab" if offset else "wb") as f_out:
            while chunk := response.read(CHUNK_SIZE):
                f_out.write(chunk)
                written += len(chunk)
                if written >= next_report:
                    progress = f"{written / 1e9:.1f} GB"
                    if total:
                        progress += f" / {total / 1e9:.1f} GB"
                    logging.info(progress)
                    next_report = written + 1024 * CHUNK_SIZE
    os.replace(part, dest)


def _gunzip(src: str, dest: str):
    with gzip.open(src, "rb") as f_in, open(dest, "wb") as f_out:
        shutil.copyfileobj(f_in, f_out, CHUNK_SIZE)


def _safe_path(root: str, name: str) -> str:
    """Rejects archive members that would escape root"""
    path = os.path.realpath(os.path.join(root, name))
    if os.path.commonpath([path, os.path.realpath(root)]) != os.path.realpath(root):
        raise Exception(f"Unsafe archive member path: {name}")
    return path


def _extract_tar(archive: str, pattern: str, dest_dir: str, flatten: bool):
    with tarfile.open(archive) as tar:
        for member in tar:
            if not member.isfile() or not fnmatch.fnmatch(
                os.path.basename(member.name), pattern
            ):
                continue
            name = os.path.basename(member.name) if flatten else member.name
            path = _safe_path(dest_dir, name)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with tar.extractfile(member) as f_in, open(path, "wb") as f_out:
                shutil.copyfileobj(f_in, f_out, CHUNK_SIZE)


def _extract_zip(archive: str, pattern: str, dest_dir: str):
    with zipfile.ZipFile(archive) as zf:
        for info in zf.infolist():
            name = os.path.basename(info.filename)
            if info.is_dir() or not fnmatch.fnmatch(name, pattern):
                continue
            with zf.open(info) as f_in, open(
                _safe_path(dest_dir, name), "wb"
            ) as f_out:
                shutil.copyfileobj(f_in, f_out, CHUNK_SIZE)


def is_present(source: Source) -> bool:
    if source.kind in ("rsync", "tar_dir", "zip_dir", "manual"):
        return os.path.isdir(source.target) and any(os.scandir(source.target))
    return os.path.exists(source.target)


def download(source: Source, keep_archives: bool):
    target = source.target
    if source.kind == "rsync":
        os.makedirs(target, exist_ok=True)
        subprocess.run(
            ["rsync", "-rlpt", "-v", "-z", "--delete", source.url, target + "/"],
            check=True,
        )
        return

    if source.kind == "file":
        _fetch(source.url, target)
    else:
        parent = target if source.kind.endswith("_dir") else os.path.dirname(target)
        os.makedirs(parent, exist_ok=True)
        archive = os.path.join(parent, os.path.basename(source.url))
        if not os.path.exists(archive):
            _fetch(source.url, archive)

        logging.info(f"Extracting {archive}")
        match source.kind:
            case "gunzip":
                _gunzip(archive, target)
            case "zip_member":
                _extract_zip(archive, source.member, parent)
            case "zip_dir":
                _extract_zip(archive, source.member, target)
            case "tar_member":
                _extract_tar(archive, source.member, parent, flatten=True)
                extracted = os.path.join(parent, source.member)
                if extracted != target:
                    if extracted.endswith(".gz") and not target.endswith(".gz"):
                        _gunzip(extracted, target)
                        os.remove(extracted)
                    else:
                        os.replace(extracted, target)
            case "tar_dir":
                # keep the archive's folder structure for VEP caches,
                # flatten for AlphaFold models
                _extract_tar(
                    archive, source.member, target, flatten=source.member != "*"
                )
            case _:
                raise Exception(f"Unexpected source kind: {source.kind}")
        if not keep_archives:
            os.remove(archive)

    for url in source.extra_urls:
        _fetch(url, os.path.join(os.path.dirname(target), os.path.basename(url)))


def check_url(source: Source) -> str:
    if source.kind == "rsync":
        result = subprocess.run(
            ["rsync", "--list-only", source.url],
            capture_output=True,
            text=True,
            timeout=120,
        )
        return "OK" if result.returncode == 0 else result.stderr.strip()
    try:
        request = urllib.request.Request(
            source.url, method="HEAD", headers={"User-Agent": "multiomicskg"}
        )
        with urllib.request.urlopen(request, timeout=60) as response:
            size = response.headers.get("Content-Length")
            return f"OK ({int(size) / 1e9:.2f} GB)" if size else "OK"
    except Exception as e:
        return f"FAILED: {e}"


if __name__ == "__main__":
    logging.getLogger().setLevel(logging.INFO)

    parser = argparse.ArgumentParser(
        description="Downloads the source datasets referenced by filenames.FileNames",
    )
    parser.add_argument(
        "-d",
        required=True,
        type=str,
        dest="datastore_prefix",
        help="path of the data store, e.g.: /Users/myuser/datastore",
    )
    parser.add_argument(
        "--only",
        nargs="+",
        default=None,
        help="download only these sources, e.g.: clinvar_datafile ppins/string",
    )
    parser.add_argument(
        "--skip-large",
        action="store_true",
        help="skip very large sources (gnomAD, PDB, AlphaFold, VEP cache, ...)",
    )
    parser.add_argument(
        "--force", action="store_true", help="re-download sources already present"
    )
    parser.add_argument(
        "--keep-archives",
        action="store_true",
        help="keep downloaded archives after extraction",
    )
    parser.add_argument(
        "--list", action="store_true", help="list sources and targets, then exit"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="check that each source URL is reachable, then exit",
    )
    args = parser.parse_args()

    fn = filenames.FileNames(args.datastore_prefix, "")
    sources = build_sources(fn)
    if args.only:
        unknown = set(args.only) - {s.name for s in sources}
        if unknown:
            parser.error(f"unknown sources: {', '.join(sorted(unknown))}")
        sources = [s for s in sources if s.name in args.only]

    if args.list:
        for s in sources:
            print(f"{s.name:35} {s.kind:10} {s.target}")
        raise SystemExit(0)

    if args.check:
        for s in sources:
            if s.kind != "manual":
                print(f"{s.name:35} {check_url(s)}")
        raise SystemExit(0)

    failed = []
    manual = []
    for s in sources:
        if s.kind == "manual":
            if not is_present(s):
                manual.append(s)
            continue
        if s.large and args.skip_large:
            logging.info(f"Skipping large source {s.name}")
            continue
        if is_present(s) and not args.force:
            logging.info(f"{s.name} already present at {s.target}")
            continue
        if s.note:
            logging.warning(f"{s.name}: {s.note}")
        try:
            download(s, args.keep_archives)
        except Exception as e:
            logging.error(f"Failed to download {s.name}: {e}")
            failed.append(s.name)

    for s in manual:
        logging.warning(f"Manual step for {s.name} -> {s.target}: {s.note}")
    if failed:
        logging.error(f"Failed sources: {', '.join(failed)}")
        raise SystemExit(1)
